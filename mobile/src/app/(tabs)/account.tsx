import { Linking, ScrollView, Text, View } from "react-native";
import { Button, Card, Chip, H, P, Skeleton } from "@/components/ui";
import { API_URL } from "@/lib/api";
import { useSession } from "@/lib/session";
import { supabase } from "@/lib/supabase";
import { T } from "@/lib/theme";

// Note: no purchase buttons or upgrade links in the app (App Store and Play
// rules for digital subscriptions). Plans are managed on the web until
// in-app purchases are added (see docs/12Billing.md, section 5).
export default function Account() {
  const { account } = useSession();
  return (
    <ScrollView contentContainerStyle={{ padding: 16, gap: 14 }}>
      {!account ? <Skeleton h={160} r={14} /> : (
        <Card>
          <P muted small>Signed in as</P>
          <Text style={{ color: T.text, fontSize: 16, fontWeight: "700" }}>{account.user.email}</Text>
          <View style={{ flexDirection: "row", gap: 8, marginTop: 6 }}>
            <Chip label={`${account.plan.name} plan`} tone="accent" />
            <Chip label={account.plan.model} />
          </View>
          <Meter label="Briefs this month" used={account.usage.briefs} limit={account.limits.briefs} />
          {account.limits.searches > 0 && <Meter label="Web searches" used={account.usage.searches} limit={account.limits.searches} />}
        </Card>
      )}
      <Card>
        <H size={15}>Privacy</H>
        <P small>Your workspace is private to your account. EMMA's replies are generated by Anthropic's Claude; your data isn't used to train AI models.</P>
        <Text onPress={() => Linking.openURL(`${API_URL}/legal/privacy`)} accessibilityRole="link" style={{ color: T.accent }}>Privacy policy</Text>
        <Text onPress={() => Linking.openURL(`${API_URL}/legal/terms`)} accessibilityRole="link" style={{ color: T.accent }}>Terms</Text>
      </Card>
      <Button label="Sign out" kind="danger" onPress={() => supabase.auth.signOut()} />
    </ScrollView>
  );
}

function Meter({ label, used, limit }: { label: string; used: number; limit: number }) {
  const v = limit ? Math.min(1, used / limit) : 0;
  return (
    <View style={{ gap: 6, marginTop: 8 }} accessible accessibilityLabel={`${label}: ${used} of ${limit}`}>
      <View style={{ flexDirection: "row", justifyContent: "space-between" }}>
        <Text style={{ color: T.text2, fontSize: 13 }}>{label}</Text>
        <Text style={{ color: T.text2, fontSize: 13, fontVariant: ["tabular-nums"] }}>{used}/{limit}</Text>
      </View>
      <View style={{ height: 6, borderRadius: 6, backgroundColor: "rgba(148,170,220,0.1)", overflow: "hidden" }}>
        <View style={{ height: 6, width: `${v * 100}%`, backgroundColor: v >= 0.8 ? T.warn : T.aiFrom }} />
      </View>
    </View>
  );
}
